const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  getConfig: () => ipcRenderer.invoke('get-config'),
  detectSteam: () => ipcRenderer.invoke('detect-steam'),
  saveConfig: (config) => ipcRenderer.invoke('save-config', config),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  discoverMods: (config) => ipcRenderer.invoke('discover-mods', config),
  saveLoadOrder: (data) => ipcRenderer.invoke('save-load-order', data),
  getPacks: () => ipcRenderer.invoke('get-packs'),
  savePack: (pack) => ipcRenderer.invoke('save-pack', pack),
  deletePack: (name) => ipcRenderer.invoke('delete-pack', name),
  fetchWorkshopDetails: (ids) => ipcRenderer.invoke('fetch-workshop-details', ids),
  translateTexts: (texts, sl, tl) => ipcRenderer.invoke('translate-texts', texts, sl, tl),
  loadModDatabase: () => ipcRenderer.invoke('load-mod-database'),
  saveModDatabase: (data) => ipcRenderer.invoke('save-mod-database', data),
  openFileDialog: (filters) => ipcRenderer.invoke('open-file-dialog', filters),
  saveFileDialog: (name) => ipcRenderer.invoke('save-file-dialog', name),
  writeFile: (path, content) => ipcRenderer.invoke('write-file', path, content),
  generateConflicts: (activeMods, gamePath) => ipcRenderer.invoke('generate-conflicts', activeMods, gamePath),
  diffSector: (zonePath, gamePath, zx, zy) => ipcRenderer.invoke('diff-sector', zonePath, gamePath, zx, zy),
  diffSectorConflict: (zonePathsByMod, gamePath, zx, zy) => ipcRenderer.invoke('diff-sector-conflict', zonePathsByMod, gamePath, zx, zy),
  checkForUpdate: () => ipcRenderer.invoke('check-for-update'),
  downloadUpdate: (url) => ipcRenderer.invoke('download-update', url),
  launchGame: (gamePath, mode) => ipcRenderer.invoke('launch-game', gamePath, mode),
  rekenshiStatus: (gamePath) => ipcRenderer.invoke('rekenshi-status', gamePath),
  launchFcs: (gamePath) => ipcRenderer.invoke('launch-fcs', gamePath),
  openModsFolder: (gamePath) => ipcRenderer.invoke('open-mods-folder', gamePath),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  showInFolder: (filePath) => ipcRenderer.invoke('show-in-folder', filePath),
  checkModLinks: (data) => ipcRenderer.invoke('check-mod-links', data),
  createModLinks: (data) => ipcRenderer.invoke('create-mod-links', data),
  removeModLinks: (data) => ipcRenderer.invoke('remove-mod-links', data),
  relaunchAsAdmin: () => ipcRenderer.invoke('relaunch-as-admin'),
  setAppMenu: (labels) => ipcRenderer.invoke('set-app-menu', labels),
  onMenuCommand: (callback) => ipcRenderer.on('menu-command', (_event, command) => callback(command)),
  onZoomChanged: (callback) => ipcRenderer.on('zoom-changed', (_event, factor) => callback(factor)),
  onMenuBarChanged: (callback) => ipcRenderer.on('menu-bar-changed', (_event, fixed) => callback(fixed)),
  setZoom: (factor) => ipcRenderer.invoke('set-zoom', factor),
  nativeEdit: (command) => ipcRenderer.invoke('native-edit', command),
  onConfirmClose: (callback) => ipcRenderer.on('confirm-close', () => callback()),
  closeAck: () => ipcRenderer.invoke('close-ack'),
  closeNow: () => ipcRenderer.invoke('close-now'),
  openFolder: (dir) => ipcRenderer.invoke('open-folder', dir),
  openInFcs: (gamePath, file) => ipcRenderer.invoke('open-in-fcs', gamePath, file),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  readText: () => ipcRenderer.invoke('read-text'),
  // A mod list as one string 'BEEP1:…' (lib/list-string.js).
  listStrEncode: (text) => ipcRenderer.invoke('list-str-encode', text),
  listStrLooks: (text) => ipcRenderer.invoke('list-str-looks', text),
  listStrDecode: (text) => ipcRenderer.invoke('list-str-decode', text),
  listStrSave: (text, name) => ipcRenderer.invoke('list-str-save', text, name),
  resetWindow: () => ipcRenderer.invoke('reset-window'),
  softDelete: (items) => ipcRenderer.invoke('soft-delete', items),
  softRestore: (moved) => ipcRenderer.invoke('soft-restore', moved),
  deleteModFiles: (args) => ipcRenderer.invoke('delete-mod-files', args),
  steamForget: (args) => ipcRenderer.invoke('steam-forget', args),
  // The translator window (lib/kmt) and the mods it makes.
  kmtOpen: (req) => ipcRenderer.invoke('kmt-open', req),
  onKmtMadeMod: (callback) => ipcRenderer.on('kmt-made-mod', (_event, info) => callback(info)),
  onKmtDock: (callback) => ipcRenderer.on('kmt-dock', (_event, info) => callback(info)),
  kmtDockClick: () => ipcRenderer.invoke('kmt-dock-click'),
  kmtDockState: () => ipcRenderer.invoke('kmt-dock-state'),
  kmtMainDialog: (rect) => ipcRenderer.invoke('kmt-main-dialog', rect),
  kmtLang: (lang) => ipcRenderer.invoke('kmt-lang', lang),
  // An exported list in its own window (lib/list-viewer.js).
  vwOpen: (req) => ipcRenderer.invoke('vw-open', req),
});
